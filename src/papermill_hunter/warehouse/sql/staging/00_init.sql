-- ============================================================================
-- 00_init.sql —— 数仓初始化：schema 与可复用宏
-- ============================================================================
-- 为什么把宏定义单独放在一个文件里？
--   数据清洗中最常见、最容易写错、也最该被复用的逻辑就是：
--     「把字符串日期解析成 DATE」「把分号分隔的多值字段拆成列表」
--   如果每个模型各写一遍，迟早会出现"这张表按 A 规则清洗、那张表按 B 规则"，
--   两份看似相同的数据对不上，而排查成本极高。
--   统一成宏 = 一处定义、全局一致。
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS intermediate;
CREATE SCHEMA IF NOT EXISTS marts;


-- ----------------------------------------------------------------------------
-- 宏 1：日期解析
-- ----------------------------------------------------------------------------
-- Retraction Watch 的日期字段格式并不统一。实测 72,453 个非空值中：
--   - 绝大多数字是 '4/20/2026 0:00'        → %m/%d/%Y %H:%M
--   - 有 1 条是   '6/24/1756 12:00:00 AM'  → %m/%d/%Y %I:%M:%S %p（带 AM/PM）
--   - 少数只有日期没有时间                  → %m/%d/%Y
--
-- 关键结论：**必须用 try_strptime 按格式逐个尝试，不能用 TRY_CAST**。
-- 我们实测过：TRY_CAST(x AS TIMESTAMP) 在这份数据上 100% 失败。
-- try_strptime 解析失败会返回 NULL 而不是抛异常，天然适合处理"脏日期"。
-- ----------------------------------------------------------------------------
CREATE OR REPLACE MACRO rw_parse_date(s) AS
    CAST(
        COALESCE(
            try_strptime(s, '%m/%d/%Y %H:%M'),
            try_strptime(s, '%m/%d/%Y %I:%M:%S %p'),
            try_strptime(s, '%m/%d/%Y')
        )
        AS DATE
    );


-- ----------------------------------------------------------------------------
-- 宏 2：多值字段拆分
-- ----------------------------------------------------------------------------
-- Retraction Watch 的 Country / Reason / Subject / Author / Institution
-- 都是分号分隔的多值字段，且**部分字段带尾分号**，例如：
--     Reason  = 'Compromised Peer Review;Rogue Editor;'
--     Subject = '(B/T) Computer Science;(PHY) Engineering - Electrical;'
-- 如果直接 split 而不处理，会得到一个空字符串元素，
-- 进而在分组统计里凭空多出一个 "(空)" 分类 —— 这类脏数据会一路污染到看板上。
--
-- 这个宏一次性完成三件事：拆分 → 去首尾空格 → 丢弃空片段。
-- 元素数 > 1 时，TRIM 还能顺带处理 Institution 字段的 '; ' 分隔形式。
-- ----------------------------------------------------------------------------
CREATE OR REPLACE MACRO rw_split(s) AS
    list_filter(
        list_transform(string_split(COALESCE(s, ''), ';'), x -> TRIM(x)),
        x -> x <> ''
    );


-- ----------------------------------------------------------------------------
-- 宏 3：文本清洗
-- ----------------------------------------------------------------------------
-- Retraction Watch 用 'unavailable' 而不是空值来表示"没有这个信息"
-- （官方文档明确说明了这一点）。如果不处理，它会被当成一个真实的取值
-- 参与统计，比如"DOI 取值 Top10"里会出现一个叫 'unavailable' 的 DOI。
-- ----------------------------------------------------------------------------
CREATE OR REPLACE MACRO rw_clean_text(s) AS
    CASE
        WHEN s IS NULL THEN NULL
        WHEN LOWER(TRIM(s)) IN ('', 'unavailable', 'n/a', 'none') THEN NULL
        ELSE TRIM(s)
    END;


-- ----------------------------------------------------------------------------
-- 宏 4：DOI 规范化
-- ----------------------------------------------------------------------------
-- DOI 是跨数据源关联的钥匙（要和 OpenAlex / Crossref 的 DOI 对上）。
-- 但同一个 DOI 在不同来源里的写法五花八门：
--     '10.1007/s11042-023-16489-1'
--     'https://doi.org/10.1007/S11042-023-16489-1'
--     'http://dx.doi.org/10.1007/s11042-023-16489-1'
-- DOI 本身**大小写不敏感**，但字符串比较是敏感的。
-- 所以统一：去掉 URL 前缀、转小写。
-- 不做这一步，join 的成功率会莫名其妙地掉一大截。
-- ----------------------------------------------------------------------------
CREATE OR REPLACE MACRO rw_normalize_doi(s) AS
    CASE
        WHEN s IS NULL THEN NULL
        WHEN LOWER(TRIM(s)) IN ('', 'unavailable', 'n/a', 'none') THEN NULL
        ELSE regexp_replace(LOWER(TRIM(s)), '^https?://(dx\.)?doi\.org/', '')
    END;


-- ----------------------------------------------------------------------------
-- 宏 5：PubMed ID 规范化
-- ----------------------------------------------------------------------------
-- 官方文档说明：没有 PubMed ID 时该字段为空白或 **0**。
-- 也就是字符串 '0' 在这里表示"缺失"而不是"ID 等于 0"。
-- 这种"用哨兵值表示缺失"的设计是数据清洗的经典陷阱：
-- 不处理的话，平均值、去重计数全都错。
-- ----------------------------------------------------------------------------
CREATE OR REPLACE MACRO rw_normalize_pmid(s) AS
    CASE
        WHEN s IS NULL THEN NULL
        WHEN TRIM(s) IN ('', '0', 'unavailable') THEN NULL
        ELSE TRIM(s)
    END;
